// Nombres de 1 a 32 caracteres: letras, números, `_`, `+` (-1) y `-`.
const SHORTCODE_RE = /:([a-z0-9_+-]{1,32}):/gi;

const TOKEN_RE = /(?:^|\s)(:([a-z0-9_+-]{1,32}))$/i;

/**
 * Detecta el `:nombre` que se está escribiendo justo antes del caret, para el
 * autocompletado. Solo cuenta si empieza el texto o va detrás de un espacio
 * (así `https://` o `10:30` no disparan sugerencias).
 */
export function getShortcodeToken(text, caret) {
  const value = String(text ?? '');
  const pos = Number.isFinite(caret) ? Math.max(0, Math.min(caret, value.length)) : value.length;
  const match = TOKEN_RE.exec(value.slice(0, pos));
  if (!match) return null;
  return { query: match[2], start: pos - match[1].length, end: pos };
}

const NAMES = Object.keys(EMOJI_SHORTCODES);

/**
 * Busca shortcodes por nombre: primero la coincidencia exacta, luego los que
 * empiezan por el texto y por último los que lo contienen. Se deduplica por
 * emoji para que los alias (`:poop:` / `:shit:`) no llenen la lista.
 */
export function searchShortcodes(query, limit = 8) {
  const q = String(query ?? '').toLowerCase().replace(/^:/, '');
  if (!q) return [];
  const results = [];
  const seen = new Set();
  const push = (name) => {
    const emoji = EMOJI_SHORTCODES[name];
    if (!emoji || seen.has(emoji)) return;
    seen.add(emoji);
    results.push({ name, emoji });
  };
  // Los nombres más cortos primero: con «sm» conviene `:smile:` antes que
  // `:smiling_face_with_three_hearts:`.
  const byLength = (a, b) => a.length - b.length || a.localeCompare(b);
  if (EMOJI_SHORTCODES[q]) push(q);
  NAMES.filter((name) => name.startsWith(q)).sort(byLength).forEach(push);
  NAMES.filter((name) => !name.startsWith(q) && name.includes(q)).sort(byLength).forEach(push);
  return results.slice(0, limit);
}

/**
 * Sustituye los shortcodes conocidos por su emoji. Los desconocidos se dejan
 * igual, así `10:30:` o `:noexiste:` no se rompen.
 */
export function replaceShortcodes(text) {
  const value = String(text ?? '');
  if (!value.includes(':')) return value;
  return value.replace(SHORTCODE_RE, (match, name) => {
    const emoji = EMOJI_SHORTCODES[name.toLowerCase()];
    return emoji ?? match;
  });
}
